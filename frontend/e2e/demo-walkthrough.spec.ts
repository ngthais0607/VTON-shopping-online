import { test, expect } from '@playwright/test';

test.use({ video: 'on', viewport: { width: 1280, height: 800 } });
test('record the seeded clothing shop demo', async ({ page, request }) => {
  test.skip(process.env.RUN_DEMO_WALKTHROUGH !== '1', 'Opt-in local demo recording');
  page.setDefaultTimeout(20000);
  const api = process.env.E2E_API_URL!;
  const password = process.env.DEMO_CUSTOMER_PASSWORD || 'DemoCustomer!482';
  const adminPassword = process.env.DEMO_ADMIN_PASSWORD || 'DemoAdmin!482';
  await page.goto('/login');
  await page.getByPlaceholder('Email or Username').fill('user@example.com');
  await page.getByPlaceholder('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await page.waitForURL('**/store');
  await expect(page.getByRole('heading', { name: 'Quần áo cho phong cách mỗi ngày.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/demo-catalog.png', fullPage: true });
  await page.goto('/store/products/ao-thun-cotton-compact-basic');
  await page.getByRole('button', { name: 'Size M', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).click();
  await page.goto('/store/products/ao-so-mi-oxford-dai-tay');
  await page.getByRole('button', { name: 'Size M', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).click();
  await page.goto('/store/checkout');
  await page.getByPlaceholder('John Doe').fill('Demo Customer');
  await page.getByPlaceholder('+84 987 654 321').fill('0912345678');
  await page.getByPlaceholder('123 Commerce St, District 1, Ho Chi Minh City').fill('72 Le Thanh Ton, Quan 1, TP Ho Chi Minh');
  await page.screenshot({ path: 'test-results/demo-checkout.png', fullPage: true });
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/orders/checkout-cart') && r.request().method() === 'POST');
  await page.getByRole('button', { name: /Place Order/ }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(201);
  const checkout = await response.json();
  expect(checkout.payment_method).toBe('cod');
  expect(checkout.orders.length).toBeGreaterThan(0);
  await page.waitForURL('**/store/orders/success**');
  await page.goto('/store/orders');
  await expect(page.getByRole('button', { name: 'Cancel Order' }).first()).toBeVisible();
  page.once('dialog', d => d.accept());
  const cancelPromise = page.waitForResponse(r => r.url().endsWith('/cancel') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Cancel Order' }).first().click();
  expect((await cancelPromise).status()).toBe(200);
  await page.screenshot({ path: 'test-results/demo-orders.png', fullPage: true });
  await page.goto('/store/account');
  await page.getByRole('button', { name: /Saved on this browser/ }).click();
  await expect(page.getByText(/not synced to your account or other devices/)).toBeVisible();

  // End the customer session before switching to the admin account.
  await page.goto('/store');
  await page.getByRole('button', { name: 'D Demo', exact: true }).click();
  const logoutResponse = page.waitForResponse(r => r.url().endsWith('/users/logout'));
  await page.getByRole('button', { name: 'Sign Out', exact: true }).click();
  expect((await logoutResponse).status()).toBe(204);
  await page.goto('/login');
  await page.getByPlaceholder('Email or Username').fill('admin@example.com');
  await page.getByPlaceholder('Password', { exact: true }).fill(adminPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await page.waitForURL('**/dashboard');
  await expect(page.getByText(/Dashboard/).first()).toBeVisible();
  await expect(page.getByText('Total Products', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/demo-dashboard.png', fullPage: true });
  await page.goto('/settings');
  await expect(page.getByRole('tab', { name: /Store Settings/ })).toHaveCount(0);
  await page.getByRole('tab', { name: /Security/ }).click();
  await expect(page.getByRole('button', { name: 'Update Password' })).toBeVisible();
  await page.goto('/store/contact');
  await expect(page.getByText(/No support inbox/)).toBeVisible();
  await expect(page.locator('form')).toHaveCount(0);
  const catalog = await (await request.get(`${api}/products?limit=100`)).json();
  expect(catalog.total).toBe(12);
  expect(catalog.items.every((p: { available_stock: number }) => p.available_stock > 0)).toBe(true);
});
